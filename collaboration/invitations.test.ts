import {convexTest} from 'convex-test';
import {it,expect,vi,afterEach} from 'vitest';
import {registerCore,sessionIdentity} from '@convex-dev/auth/test';
import {registerPassword} from '@convex-dev/auth/components/password/test';
import {registerUsername} from '@convex-dev/auth/components/username/test';
import schema from '../convex/schema';
import {api} from '../convex/_generated/api';
const modules=import.meta.glob('../convex/**/*.ts');
afterEach(()=>vi.unstubAllEnvs());
it('invitation autocomplete finds existing accounts, restricts owners and omits private fields and existing members',async()=>{
 vi.stubEnv('CONVEX_CLOUD_URL','https://test.convex.cloud');
 const t=convexTest(schema,modules);registerCore(t);registerPassword(t);registerUsername(t);
 const account=async(username:string)=>{const r=await t.mutation(api.auth.signUpWithUsernamePassword,{username,password:'unique-invite-test-password-9384'});if(r.status!=='complete')throw Error('Signup failed');return t.withIdentity(sessionIdentity(r.tokens));};
 const owner=await account('owner'),alex=await account('alex'),alice=await account('alice');
 await alice.mutation(api.accounts.updateProfile,{name:'Alice Example',color:'#123456',background:'private background'});
 const boardId=await owner.mutation(api.library.create,{title:'Test'}),teamId=await owner.mutation(api.teams.create,{name:'Team'});
 const query={boardId,prefix:' @AL '};
 expect((await owner.query(api.invitations.suggestions,query)).map(x=>x.username)).toEqual(['alex','alice']);
 expect(await owner.query(api.invitations.suggestions,{boardId,prefix:'a'})).toEqual([]);
 expect(await owner.query(api.invitations.suggestions,{boardId,prefix:'zz'})).toEqual([]);
 await expect(t.query(api.invitations.suggestions,query)).rejects.toThrow();
 await expect(alex.query(api.invitations.suggestions,query)).rejects.toThrow();
 await owner.mutation(api.sharing.addMember,{boardId,username:'alex',role:'editor'});
 await expect(alex.query(api.invitations.suggestions,query)).rejects.toThrow();
 const matches=await owner.query(api.invitations.suggestions,query);
 expect(matches).toHaveLength(1);expect(matches[0]).toMatchObject({username:'alice',name:'Alice Example'});
 expect(Object.keys(matches[0]).sort()).toEqual(['color','name','userId','username']);
 await owner.mutation(api.teams.addMember,{teamId,username:'alice'});
 expect((await owner.query(api.invitations.suggestions,{teamId,prefix:'al'})).map(x=>x.username)).toEqual(['alex']);
 await expect(alice.query(api.invitations.suggestions,{teamId,prefix:'al'})).rejects.toThrow();
 await owner.mutation(api.teams.moveBoard,{boardId,teamId});
 expect(await owner.query(api.invitations.suggestions,query)).toEqual([]);
});
