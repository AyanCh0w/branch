import {convexTest} from 'convex-test';
import {it,expect,vi,afterEach} from 'vitest';
import schema from '../convex/schema';
import {api} from '../convex/_generated/api';
const modules=import.meta.glob('../convex/**/*.ts');
afterEach(()=>{vi.unstubAllEnvs();vi.useRealTimers();});
it('shares authorized human positions, permits viewers, isolates sessions and expires presence without locking edits',async()=>{
 vi.useFakeTimers();vi.stubEnv('DEV_BRIDGE_SECRET','test');vi.stubEnv('ENABLE_DEVELOPMENT_BRIDGE','true');
 const t=convexTest(schema,modules);
 const alice=await t.mutation(api.boards.developmentSession,{secret:'test',identityKey:'alice',token:'alice'});
 const bob=await t.mutation(api.boards.developmentSession,{secret:'test',identityKey:'bob',token:'bob',boardId:alice.boardId});
 const a={token:'alice',boardId:alice.boardId},b={token:'bob',boardId:alice.boardId};
 await t.run(async ctx=>{const member=await ctx.db.query('boardMembers').withIndex('board_user',q=>q.eq('boardId',alice.boardId).eq('userId',bob.userId)).unique();await ctx.db.patch(member!._id,{role:'viewer'});});
 await t.mutation(api.collaboration.point,{...b,tabId:'same-tab',position:{x:123,y:-456}});
 expect(await t.query(api.collaboration.cursors,a)).toMatchObject([{x:123,y:-456,userId:bob.userId}]);
 expect(await t.query(api.collaboration.cursors,b)).toEqual([]);
 expect(await t.query(api.collaboration.editors,a)).toEqual([]);
 await t.mutation(api.collaboration.point,{...a,tabId:'same-tab',position:null});
 expect(await t.query(api.collaboration.cursors,a)).toHaveLength(1);
 await expect(t.mutation(api.collaboration.point,{...b,position:{x:Infinity,y:0},tabId:'bad'})).rejects.toThrow();
 await expect(t.query(api.collaboration.cursors,{...a,token:'invalid'})).rejects.toThrow();
 await t.mutation(api.collaboration.point,{...b,tabId:'same-tab',position:{x:8,y:9}});
 expect(await t.query(api.collaboration.cursors,a)).toMatchObject([{x:8,y:9}]);
 vi.advanceTimersByTime(15001);
 expect(await t.query(api.collaboration.cursors,a)).toEqual([]);
 await t.mutation(api.collaboration.point,{...b,tabId:'same-tab',position:{x:1,y:2}});
 expect(await t.run(ctx=>ctx.db.query('cursors').collect())).toHaveLength(1);
 await t.run(async ctx=>{const member=await ctx.db.query('boardMembers').withIndex('board_user',q=>q.eq('boardId',alice.boardId).eq('userId',bob.userId)).unique();await ctx.db.delete(member!._id);});
 expect(await t.query(api.collaboration.cursors,a)).toEqual([]);
 await expect(t.mutation(api.collaboration.point,{...b,tabId:'same-tab',position:{x:1,y:2}})).rejects.toThrow('Board access denied');
});
