import {convexTest} from 'convex-test';
import {it,expect,vi,afterEach} from 'vitest';
import schema from '../convex/schema';
import {api} from '../convex/_generated/api';
const modules=import.meta.glob('../convex/**/*.ts');
afterEach(()=>{vi.unstubAllEnvs();vi.useRealTimers();});
it('lists people once, preserves other tabs, expires attendance and filters revoked access',async()=>{
 vi.useFakeTimers();vi.stubEnv('DEV_BRIDGE_SECRET','test');vi.stubEnv('ENABLE_DEVELOPMENT_BRIDGE','true');
 const t=convexTest(schema,modules);
 const alice=await t.mutation(api.boards.developmentSession,{secret:'test',identityKey:'alice',token:'alice'});
 const bob=await t.mutation(api.boards.developmentSession,{secret:'test',identityKey:'bob',token:'bob',boardId:alice.boardId});
 const a={token:'alice',boardId:alice.boardId},b={token:'bob',boardId:alice.boardId};
 await t.run(async ctx=>{const row=await ctx.db.query('boardMembers').withIndex('board_user',q=>q.eq('boardId',alice.boardId).eq('userId',bob.userId)).unique();await ctx.db.patch(row!._id,{role:'viewer'});});
 for(const tabId of ['one','two'])await t.mutation(api.collaboration.attend,{...b,tabId,active:true});
 await t.mutation(api.collaboration.attend,{...a,tabId:'one',active:true});
 expect(await t.query(api.collaboration.activeUsers,a)).toHaveLength(2);
 expect(await t.query(api.collaboration.editors,a)).toEqual([]);
 expect(await t.query(api.collaboration.cursors,a)).toEqual([]);
 await t.mutation(api.collaboration.attend,{...b,tabId:'one',active:false});
 expect(await t.query(api.collaboration.activeUsers,a)).toHaveLength(2);
 await t.mutation(api.collaboration.attend,{...b,tabId:'two',active:false});
 expect(await t.query(api.collaboration.activeUsers,a)).toMatchObject([{userId:alice.userId}]);
 vi.advanceTimersByTime(15001);
 expect(await t.query(api.collaboration.activeUsers,a)).toEqual([]);
 await t.mutation(api.collaboration.attend,{...b,tabId:'two',active:true});
 expect(await t.run(ctx=>ctx.db.query('boardPresence').collect())).toHaveLength(1);
 await t.run(async ctx=>{const row=await ctx.db.query('boardMembers').withIndex('board_user',q=>q.eq('boardId',alice.boardId).eq('userId',bob.userId)).unique();await ctx.db.delete(row!._id);});
 expect(await t.query(api.collaboration.activeUsers,a)).toEqual([]);
 await expect(t.mutation(api.collaboration.attend,{...b,tabId:'two',active:true})).rejects.toThrow('Board access denied');
 await expect(t.query(api.collaboration.activeUsers,{...a,token:'invalid'})).rejects.toThrow();
});
