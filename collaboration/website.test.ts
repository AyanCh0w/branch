import {convexTest} from 'convex-test';
import {it,expect,vi,afterEach} from 'vitest';
import {createRequire} from 'node:module';
import * as Y from 'yjs';
import schema from '../convex/schema';
import {api,internal} from '../convex/_generated/api';
import {loadDocument} from '../convex/documents';
const {snapshotNode}=createRequire(import.meta.url)('../ux-prototype/context.js');
const modules=import.meta.glob('../convex/**/*.ts');
afterEach(()=>{vi.unstubAllEnvs();vi.useRealTimers();});
it('perspective notes persist through shared editing and enter a frozen AI run',async()=>{
 vi.useFakeTimers();vi.stubEnv('DEV_BRIDGE_SECRET','website-test-secret');vi.stubEnv('ENABLE_DEVELOPMENT_BRIDGE','true');
 const t=convexTest(schema,modules);
 const session=await t.mutation(api.boards.developmentSession,{secret:'website-test-secret',identityKey:'website-tester',token:'website-test-token'});
 const auth={boardId:session.boardId,token:'website-test-token'};
 await t.mutation(api.boards.initialize,{...auth,title:'Website perspectives',nodes:[{id:'site',type:'web',title:'Hackathon',url:'https://hackathon.example',body:'',x:0,y:0},{id:'chat',type:'thread',title:'Project ideas',draft:'Suggest a project for me.',messages:[],contexts:[],x:500,y:0}]});
 let board=await t.query(api.boards.read,auth),site=board.nodes.find(n=>n.id==='site')!;
 const doc=loadDocument(site.sharedTextState),vector=Y.encodeStateVector(doc);
 doc.getText('body').insert(0,'I am an attendee, not an organizer. I want to build a prototype.');
 await t.mutation(api.collaboration.updateText,{...auth,nodeKey:'site',tabId:'website-tab',epoch:0,update:Uint8Array.from(Y.encodeStateAsUpdate(doc,vector)).buffer});
 board=await t.query(api.boards.read,auth);site=board.nodes.find(n=>n.id==='site')!;
 expect(site.body).toContain('I am an attendee');
 const context=snapshotNode(site,board.nodes);
 await t.mutation(api.boards.patchNodes,{...auth,changes:[{id:'chat',patch:{contexts:[context]}}]});
 const runId=await t.mutation(api.chat.send,{...auth,nodeKey:'chat',requestId:'website-perspective-run',expectedVersion:0});
 const run=await t.run(ctx=>ctx.db.get(runId));
 expect(run!.input.contexts[0].text).toContain('https://hackathon.example');
 expect(run!.input.contexts[0].text).toContain('I am an attendee, not an organizer');
 expect(run!.input.contexts[0].text).toContain('not extracted website text');
 expect(run!.billedUserId).toBe(session.userId);
 await t.mutation(internal.chat.append,{runId,text:'',activity:'searching'});
 expect((await t.query(api.boards.read,auth)).nodes.find(n=>n.id==='chat')!.activity).toBe('searching');
 await t.mutation(internal.chat.append,{runId,text:'Partial reply',activity:'writing'});
 await t.mutation(internal.chat.append,{runId,text:'',done:true,finalText:'A project for attendees. [Hackathon](https://hackathon.example)'});
 const completed=await t.query(api.boards.read,auth);
 const answer=completed.nodes.find(n=>n.id==='chat')!.messages.at(-1);
 expect(answer.text).toBe('A project for attendees. [Hackathon](https://hackathon.example)');
 expect(completed.nodes.find(n=>n.id==='chat')!.activeRun).toBeUndefined();
 expect(completed.nodes.find(n=>n.id==='chat')!.activity).toBeUndefined();
 doc.destroy();
});
