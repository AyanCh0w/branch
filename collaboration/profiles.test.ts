import {convexTest} from 'convex-test';
import {it,expect,vi,afterEach} from 'vitest';
import {registerCore,sessionIdentity} from '@convex-dev/auth/test';
import {registerPassword} from '@convex-dev/auth/components/password/test';
import {registerUsername} from '@convex-dev/auth/components/username/test';
import schema from '../convex/schema';
import {api} from '../convex/_generated/api';
const modules=import.meta.glob('../convex/**/*.ts');
afterEach(()=>{vi.unstubAllEnvs();vi.useRealTimers();});
it('keeps background private, enforces role ownership and freezes sender context at Send',async()=>{
 vi.useFakeTimers();vi.stubEnv('CONVEX_CLOUD_URL','https://test.convex.cloud');
 const t=convexTest(schema,modules);registerCore(t);registerPassword(t);registerUsername(t);
 async function account(username:string){const result=await t.mutation(api.auth.signUpWithUsernamePassword,{username,password:'unique-profile-test-password-9384'});if(result.status!=='complete')throw Error('Signup failed');return t.withIdentity(sessionIdentity(result.tokens));}
 const owner=await account('profileowner'),member=await account('profilemember'),outsider=await account('profileoutsider');
 await owner.mutation(api.accounts.updateProfile,{name:'Alex',color:'#dd7733',background:'Private owner background'});
 await member.mutation(api.accounts.updateProfile,{name:'Sam',color:'#228855',background:'I study usability'});
 expect(await member.query(api.accounts.me,{})).toMatchObject({name:'Sam',color:'#228855',background:'I study usability'});
 await expect(member.mutation(api.accounts.updateProfile,{name:' ',color:'#228855',background:''})).rejects.toThrow();
 await expect(member.mutation(api.accounts.updateProfile,{name:'Sam',color:'red',background:''})).rejects.toThrow();
 const teamId=await owner.mutation(api.teams.create,{name:'Studio'});
 await owner.mutation(api.teams.addMember,{teamId,username:'profilemember',responsibility:'Research'});
 const details=await member.query(api.teams.details,{teamId}),self=details.members.find(m=>!m.isOwner)!,boss=details.members.find(m=>m.isOwner)!;
 expect(JSON.stringify(details)).not.toContain('Private owner background');
 await member.mutation(api.teams.setResponsibility,{memberId:self.id,responsibility:'Research and interviews'});
 await expect(member.mutation(api.teams.setResponsibility,{memberId:boss.id,responsibility:'CEO'})).rejects.toThrow();
 await expect(outsider.mutation(api.teams.setResponsibility,{memberId:self.id,responsibility:'CEO'})).rejects.toThrow();
 const boardId=await owner.mutation(api.library.create,{title:'Plan',teamId});
 await owner.mutation(api.sharing.addMember,{boardId,username:'profilemember',role:'editor',responsibility:'Usability lead'});
 const roster=await member.query(api.people.roster,{boardId}),memberId=(await owner.query(api.sharing.settings,{boardId})).members.find(m=>m.name==='Sam')!.id;
 await member.mutation(api.people.setResponsibility,{boardId,userId:roster.find(m=>m.name==='Sam')!.userId,responsibility:'Usability testing'});
 await expect(outsider.mutation(api.people.setResponsibility,{boardId,userId:roster[0].userId,responsibility:'CEO'})).rejects.toThrow();
 await member.mutation(api.boards.patchNodes,{token:'',boardId,changes:[{id:'chat',create:{id:'chat',type:'thread',title:'Chat',draft:'Plan next week',messages:[],contexts:[],x:0,y:0}}]});
 const runId=await member.mutation(api.chat.send,{token:'',boardId,nodeKey:'chat',requestId:'profile-context',expectedVersion:0});
 const visible=await member.query(api.boards.read,{boardId,token:''});
 expect(JSON.stringify(visible)).not.toContain('I study usability');
 const frozen=JSON.stringify((await t.run(ctx=>ctx.db.get(runId)))!.input.contexts);
 expect(frozen).toContain('I study usability');expect(frozen).toContain('Usability testing');expect(frozen).not.toContain('Private owner background');
 await member.mutation(api.accounts.updateProfile,{name:'Sam',color:'#228855',background:'New background'});
 expect(JSON.stringify((await t.run(ctx=>ctx.db.get(runId)))!.input.contexts)).toBe(frozen);
 await owner.mutation(api.teams.removeMember,{memberId:self.id});
 await owner.mutation(api.sharing.removeMember,{memberId});
 expect(JSON.stringify(await owner.query(api.people.context,{token:'',boardId}))).not.toContain('Usability testing');
 await expect(member.query(api.people.context,{token:'',boardId})).rejects.toThrow();
});
