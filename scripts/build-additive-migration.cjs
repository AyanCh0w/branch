// Generate an additive migration for entities added to backend/schema.ts since
// backend/entities.json was last written. New tables, new optional columns and
// new indexes only: nothing existing is dropped, renamed or rewritten.
// Usage: npm run build:backend && node scripts/build-additive-migration.cjs <name>
// Inspect the generated SQL before applying; this never connects to a database.
const fs = require('node:fs');
const name = process.argv[2];
if (!/^\d{12}_[a-z0-9_]+$/.test(name || '')) throw Error('Pass a migration name such as 202611140003_live_coordination');
const output = 'supabase/migrations/' + name + '.sql';
// A deployed migration is never regenerated.
if (fs.existsSync(output)) throw Error(output + ' already exists');
const schema = require('../backend/schema.bundle.cjs').default;
const before = JSON.parse(fs.readFileSync('backend/entities.json', 'utf8'));
const snake = s => s.replace(/[A-Z]/g, c => '_' + c.toLowerCase());
const column = key => key === 'createdAt' ? 'run_created_at' : snake(key);
const qi = s => '"' + s.replaceAll('"', '""') + '"';
const lit = s => "'" + String(s).replaceAll("'", "''") + "'";
const optional = (type, reference) => ({ optional: true, sql: { type, reference } });
schema._storage = { shape: {
  path: {sql:{type:'text'}}, size:{sql:{type:'double precision'}},
  contentType:optional('text'), ticket:optional('text','fileUploads'),
  boardId:optional('text','boards'), userId:optional('text','users'),
}, indexes:{} };
const table = n => n === '_storage' ? 'files' : snake(n);
const fields = n => Object.entries(schema[n].shape);
const names = Object.keys(schema);
// Only brand-new tables may carry unique indexes: existing rows were never checked for duplicates.
const unique = new Set(['nodeTexts.board_key','codingConnections.key','chatgptThreads.conversation','chatgptUpdates.update','workItems.card','workUpdates.update','areaDigests.board_area']);
const definition = ([key, v]) => {
  const col = qi(column(key)), type = v.sql?.type || 'jsonb', values = v.sql?.values;
  return `${col} ${type}${v.optional ? '' : ' not null'}${values ? ` check (${col} in (${values.map(lit).join(',')}))` : ''}${type === 'double precision' ? ` check (${col} > '-Infinity'::float8 and ${col} < 'Infinity'::float8)` : ''}`;
};
const sql = [`-- Additive entities for agent connections, GitHub context and live coordination.
-- Generated by scripts/build-additive-migration.cjs. Never overwrite a deployed migration.
begin;
set local lock_timeout = '15s';
select id from branch_private.runtime_lock where id=1 for update;`];
const references = [];
for (const n of names) {
  const t = qi(table(n)), known = before[n];
  if (!known) {
    sql.push(`create table branch_private.${t} (
 id text primary key references branch_private.record_ids(id) deferrable initially deferred,
 created_at double precision not null check (created_at>=0 and created_at<'Infinity'::float8),
 ${fields(n).map(definition).join(',\n ')}
);
alter table branch_private.${t} enable row level security;
create trigger register_record before insert or update on branch_private.${t} for each row execute function branch_private.register_record(${lit(n)});
create trigger unregister_record after delete on branch_private.${t} for each row execute function branch_private.register_record(${lit(n)});`);
    for (const [index, keys] of Object.entries(schema[n].indexes)) sql.push(`create ${unique.has(n + '.' + index) ? 'unique ' : ''}index ${qi(table(n) + '_' + index + '_idx')} on branch_private.${t} (${keys.map(k => qi(column(k))).join(',')});`);
    for (const [key, v] of fields(n)) if (v.sql?.reference) references.push([n, key, v]);
    continue;
  }
  for (const key of Object.keys(known.fields)) if (!schema[n].shape[key]) throw Error(`${n}.${key} was removed; additive migrations cannot drop fields`);
  for (const [key, v] of fields(n)) {
    if (known.fields[key]) continue;
    if (!v.optional) throw Error(`${n}.${key} must be optional to be added to an existing table`);
    sql.push(`alter table branch_private.${t} add column ${definition([key, v])};`);
    if (v.sql?.reference) references.push([n, key, v]);
  }
  // Index names are stable, so "if not exists" adds only the new ones.
  for (const [index, keys] of Object.entries(schema[n].indexes)) sql.push(`create index if not exists ${qi(table(n) + '_' + index + '_idx')} on branch_private.${t} (${keys.map(k => qi(column(k))).join(',')});`);
}
for (const n of Object.keys(before)) if (!schema[n]) throw Error(`${n} was removed; additive migrations cannot drop tables`);
for (const [n, key, v] of references) sql.push(`alter table branch_private.${qi(table(n))} add constraint ${qi(table(n) + '_' + column(key) + '_fk')} foreign key (${qi(column(key))}) references branch_private.${qi(table(v.sql.reference))}(id) deferrable initially deferred;`);
const jsonExpr = n => fields(n).map(([key, v]) => v.optional ? `case when ${qi(column(key))} is null then '{}'::jsonb else jsonb_build_object(${lit(key)},${qi(column(key))}) end` : `jsonb_build_object(${lit(key)},${qi(column(key))})`).join(' || ');
sql.push(`-- The compatibility view and its writer cover every entity, including the new ones.
create or replace view branch_private.records with (security_invoker=true) as
${names.map(n => `select id,${lit(n)}::text as collection,created_at,(${jsonExpr(n)}) as data from branch_private.${qi(table(n))}`).join('\nunion all\n')};`);
const cases = names.map(n => {
  const cols = fields(n).map(([key]) => qi(column(key))).join(',');
  const vals = fields(n).map(([key, v]) => (v.sql?.type || 'jsonb') === 'jsonb' ? `$1->${lit(key)}` : `($1->>${lit(key)})::${v.sql.type}`).join(',');
  return `when ${lit(n)} then target:=${lit(table(n))}; allowed:=array[${fields(n).map(([key]) => lit(key)).join(',')}]; columns_sql:=${lit(cols)}; values_sql:=${lit(vals)};`;
}).join('\n');
sql.push(`create or replace function branch_private.write_record() returns trigger language plpgsql set search_path=pg_catalog,branch_private as $$
declare target text; columns_sql text; values_sql text; allowed text[];
begin
 if TG_OP='DELETE' then
  select case old.collection ${names.map(n => `when ${lit(n)} then ${lit(table(n))}`).join(' ')} end into target;
  execute format('delete from branch_private.%I where id=$1',target) using old.id;
  return old;
 end if;
 if TG_OP='UPDATE' and (new.id is distinct from old.id or new.collection is distinct from old.collection or new.created_at is distinct from old.created_at) then raise exception 'Immutable record identity'; end if;
 if jsonb_typeof(new.data) is distinct from 'object' then raise exception 'Record must be an object'; end if;
 case new.collection
 ${cases}
 else raise exception 'Unknown collection';
 end case;
 if exists(select 1 from jsonb_object_keys(new.data) k where not k=any(allowed)) then raise exception 'Unknown record field'; end if;
 if TG_OP='INSERT' then
  execute format('insert into branch_private.%I (id,created_at,%s) select $2,$3,%s',target,columns_sql,values_sql) using new.data,new.id,new.created_at;
 else
  execute format('update branch_private.%I set (%s)=(select %s) where id=$2',target,columns_sql,values_sql) using new.data,old.id;
 end if;
 return new;
end $$;
revoke all on all tables in schema branch_private from public,anon,authenticated;
revoke all on all functions in schema branch_private from public,anon,authenticated;
set constraints all immediate;
commit;`);
fs.writeFileSync(output, sql.join('\n\n') + '\n');
fs.writeFileSync('backend/entities.json', JSON.stringify(Object.fromEntries(names.map(n => [n, { table: table(n), fields: Object.fromEntries(fields(n).map(([key, v]) => [key, { column: column(key), type: v.sql?.type || 'jsonb', optional: !!v.optional }])) }])), null, 2) + '\n');
console.log(`Wrote ${output} and refreshed backend/entities.json (${names.length} entities).`);
