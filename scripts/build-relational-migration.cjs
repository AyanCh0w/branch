// Generate the fixed migration from the application's entity definitions.
// Inspect the generated SQL before applying; this never connects to a database.
const fs = require('node:fs');
const schema = require('../backend/schema.bundle.cjs').default;
const snake = s => s.replace(/[A-Z]/g, c => '_' + c.toLowerCase());
const column = key => key === 'createdAt' ? 'run_created_at' : snake(key);
const qi = s => '"' + s.replaceAll('"', '""') + '"';
const lit = s => "'" + String(s).replaceAll("'", "''") + "'";
const optional = (type, reference) => ({ optional: true, sql: { type, reference } });
schema._storage = { shape: {
  path: {sql:{type:'text'}}, size:{sql:{type:'double precision'}},
  contentType:optional('text'), ticket:optional('text','fileUploads'),
  boardId:optional('text','boards'), userId:optional('text','users'),
}, indexes:{path:['path'],board:['boardId']} };
const table = name => name === '_storage' ? 'files' : snake(name);
const fields = name => Object.entries(schema[name].shape);
const names = Object.keys(schema);
const unique = new Set(['users.identity','teamMembers.team_user','teamInvites.token','boardMembers.board_user','projectResponsibilities.board_user','sessions.token','nodes.board_key','runs.request','boardLinks.token','chatgptConnections.user','chatgptTransactions.state','workspaceKeys.scope','fileUploads.storage','_storage.path']);
const sql = [`-- Dedicated typed entity tables; preserve all original IDs, JSON and Yjs state.
-- Generated by scripts/build-relational-migration.cjs. Never overwrite a deployed migration.
begin;
set local lock_timeout = '15s';
select id from branch_private.runtime_lock where id=1 for update;
lock table branch_private.records in access exclusive mode;
alter table branch_private.accounts drop constraint accounts_user_id_fkey;
alter table branch_private.records rename to records_legacy_backup;
create table branch_private.record_ids(id text primary key, collection text not null);
alter table branch_private.record_ids enable row level security;
create function branch_private.register_record() returns trigger language plpgsql set search_path=pg_catalog,branch_private as $$
begin
 if TG_OP='INSERT' then
  insert into branch_private.record_ids(id,collection) values(new.id,TG_ARGV[0]);
  return new;
 elsif TG_OP='UPDATE' then
  if new.id is distinct from old.id or new.created_at is distinct from old.created_at then raise exception 'Immutable record identity'; end if;
  return new;
 else
  delete from branch_private.record_ids where id=old.id;
  return old;
 end if;
end $$;`];
for (const name of names) {
  const t = qi(table(name));
  const columns = fields(name).map(([key,v]) => {
    const col=qi(column(key)), type=v.sql?.type||'jsonb';
    const values=v.sql?.values;
    return `${col} ${type}${v.optional?'':' not null'}${values?` check (${col} in (${values.map(lit).join(',')}))`:''}${type==='double precision'?` check (${col} > '-Infinity'::float8 and ${col} < 'Infinity'::float8)`:''}`;
  });
  sql.push(`create table branch_private.${t} (
 id text primary key references branch_private.record_ids(id) deferrable initially deferred,
 created_at double precision not null check (created_at>=0 and created_at<'Infinity'::float8),
 ${columns.join(',\n ')}
);
alter table branch_private.${t} enable row level security;
create trigger register_record before insert or update on branch_private.${t} for each row execute function branch_private.register_record(${lit(name)});
create trigger unregister_record after delete on branch_private.${t} for each row execute function branch_private.register_record(${lit(name)});`);
  for(const [index,keys] of Object.entries(schema[name].indexes)) {
    sql.push(`create ${unique.has(name+'.'+index)?'unique ':''}index ${qi(table(name)+'_'+index+'_idx')} on branch_private.${t} (${keys.map(k=>qi(column(k))).join(',')});`);
  }
}
for(const name of names) for(const [key,v] of fields(name)) {
  if(!v.sql?.reference)continue;
  // Runs retain a historical connection identifier even after disconnect/reconnect.
  if(name==='runs'&&key==='connectionId')continue;
  sql.push(`alter table branch_private.${qi(table(name))} add constraint ${qi(table(name)+'_'+column(key)+'_fk')} foreign key (${qi(column(key))}) references branch_private.${qi(table(v.sql.reference))}(id)${name==='chatgptTransactions'&&key==='connectionId'?' on delete set null':''} deferrable initially deferred;`);
}
sql.push(`
alter table branch_private.nodes add constraint nodes_text_version_valid check(text_version>=0);
alter table branch_private.files add constraint file_size_valid check(size>=0 and size<=26214400);
alter table branch_private.team_members add constraint team_role_valid check(role in ('owner','member'));
alter table branch_private.jobs add constraint job_status_valid check(status in ('pending','running','complete','failed'));
alter table branch_private.jobs add constraint job_attempts_valid check(attempts>=0);
create index jobs_running_lease_idx on branch_private.jobs(lease_until) where status='running';`);
const jsonExpr = name => fields(name).map(([key,v])=>v.optional?`case when ${qi(column(key))} is null then '{}'::jsonb else jsonb_build_object(${lit(key)},${qi(column(key))}) end`:`jsonb_build_object(${lit(key)},${qi(column(key))})`).join(' || ');
sql.push(`-- Compatibility view keeps the proven handler/transaction API stable.
-- These are dedicated tables with typed columns, not views over a JSON records table.
create view branch_private.records with (security_invoker=true) as
${names.map(name=>`select id,${lit(name)}::text as collection,created_at,(${jsonExpr(name)}) as data from branch_private.${qi(table(name))}`).join('\nunion all\n')};`);
const cases = names.map(name=>{
  const cols=fields(name).map(([key])=>qi(column(key))).join(',');
  const vals=fields(name).map(([key,v])=>(v.sql?.type||'jsonb')==='jsonb'?`$1->${lit(key)}`:`($1->>${lit(key)})::${v.sql.type}`).join(',');
  return `when ${lit(name)} then target:=${lit(table(name))}; allowed:=array[${fields(name).map(([key])=>lit(key)).join(',')}]; columns_sql:=${lit(cols)}; values_sql:=${lit(vals)};`;
}).join('\n');
sql.push(`create function branch_private.write_record() returns trigger language plpgsql set search_path=pg_catalog,branch_private as $$
declare target text; columns_sql text; values_sql text; allowed text[];
begin
 if TG_OP='DELETE' then
  select case old.collection ${names.map(name=>`when ${lit(name)} then ${lit(table(name))}`).join(' ')} end into target;
  execute format('delete from branch_private.%I where id=$1',target) using old.id;
  return old;
 end if;
 if TG_OP='UPDATE' and (new.id is distinct from old.id or new.collection is distinct from old.collection or new.created_at is distinct from old.created_at) then raise exception 'Immutable record identity'; end if;
 if jsonb_typeof(new.data) is distinct from 'object' then raise exception 'Record must be an object'; end if;
 case new.collection
 ${cases}
 else raise exception 'Unknown collection';
 end case;
 if exists(select 1 from jsonb_object_keys(new.data) k where not k=any(allowed)) then raise exception 'Unknown record field'; end if;
 if TG_OP='INSERT' then
  execute format('insert into branch_private.%I (id,created_at,%s) select $2,$3,%s',target,columns_sql,values_sql) using new.data,new.id,new.created_at;
 else
  -- Delete/reinsert would break references and trigger identity registration.
  execute format('update branch_private.%I set (%s)=(select %s) where id=$2',target,columns_sql,values_sql) using new.data,old.id;
 end if;
 return new;
end $$;
create trigger write_record instead of insert or update or delete on branch_private.records for each row execute function branch_private.write_record();
insert into branch_private.records(id,collection,created_at,data) select id,collection,created_at,data from branch_private.records_legacy_backup;
alter table branch_private.accounts add constraint accounts_user_id_fkey foreign key(user_id) references branch_private.users(id) deferrable initially deferred;
-- Fail the entire migration if a field, byte state, or relationship changed.
do $$ begin
 if exists((select id,collection,created_at,data from branch_private.records_legacy_backup except select id,collection,created_at,data from branch_private.records)
 union all (select id,collection,created_at,data from branch_private.records except select id,collection,created_at,data from branch_private.records_legacy_backup)) then raise exception 'Relational migration changed existing data'; end if;
end $$;
revoke all on all tables in schema branch_private from public,anon,authenticated;
revoke all on all functions in schema branch_private from public,anon,authenticated;
set constraints all immediate;
commit;`);
fs.writeFileSync('supabase/migrations/202611140002_relational_entities.sql',sql.join('\n\n')+'\n');
fs.writeFileSync('backend/entities.json',JSON.stringify(Object.fromEntries(names.map(name=>[name,{table:table(name),fields:Object.fromEntries(fields(name).map(([key,v])=>[key,{column:column(key),type:v.sql?.type||'jsonb',optional:!!v.optional}]))}])),null,2)+'\n');
console.log(`Generated ${names.length} dedicated entity tables and compatibility view.`);
